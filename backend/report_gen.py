from fpdf import FPDF
from datetime import datetime

def generate_pdf_report(results):
    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Arial", 'B', 16)
    pdf.cell(0, 10, "TECHIFY SOLUTIONS - Compliance Audit Report", ln=1, align='C')
    pdf.set_font("Arial", size=12)
    pdf.ln(10)

    pdf.cell(0, 10, f"Host: {results.get('host', 'N/A')}", ln=1)
    pdf.cell(0, 10, f"Scan Date: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}", ln=1)
    pdf.cell(0, 10, f"Compliance Score: {results.get('compliance_score', 100)}%", ln=1)
    pdf.ln(10)

    pdf.set_font("Arial", 'B', 14)
    pdf.cell(0, 10, "AI Security Insight", ln=1)
    pdf.set_font("Arial", size=12)
    pdf.multi_cell(0, 10, results.get('ai_analysis', 'No analysis available'))
    pdf.ln(10)

    pdf.set_font("Arial", 'B', 14)
    pdf.cell(0, 10, "Violations Found", ln=1)
    pdf.set_font("Arial", size=12)

    violations = results.get('violations', [])
    if not violations:
        pdf.cell(0, 10, "No violations detected - System is compliant!", ln=1)
    else:
        for v in violations:
            sev = v.get('severity', 'Low')
            title = v.get('title', 'Unknown')
            desc = v.get('description', 'No description')
            port = v.get('port')
            service = v.get('service')

            pdf.set_font("Arial", 'B', 12)
            pdf.cell(0, 10, f"{sev.upper()}: {title}", ln=1)
            pdf.set_font("Arial", size=11)
            pdf.multi_cell(0, 8, desc)
            if port:
                pdf.cell(0, 8, f"Port: {port} | Service: {service}", ln=1)
            pdf.ln(5)

    pdf.ln(10)
    pdf.set_font("Arial", size=10)
    pdf.cell(0, 10, "Report generated by TECHIFY Infrastructure Platform V2.0", ln=1, align='C')

    filename = "TECHIFY_Report.pdf"
    pdf.output(filename)
    return filename